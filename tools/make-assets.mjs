// Writes the brand files from tools/brand.mjs.
//
//   node tools/make-assets.mjs            SVG sources + PNG renders (if a renderer is installed)
//   node tools/make-assets.mjs --svg-only  only the SVG sources
//
// SVG sources are the master files and are always written. PNG renders need a renderer:
//   npm i --no-save @resvg/resvg-js
// Text in the renders needs fonts: Inter for the wordmark, Noto Sans Devanagari for the
// Hindi tagline. If `@expo-google-fonts/inter` and `@expo-google-fonts/noto-sans-devanagari`
// are installed they are picked up automatically, otherwise the system fonts are used.
// Every PNG is committed, so a normal checkout never needs this step.
import { writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import {
  iconSvg, markSvg, monoMarkSvg, lockupSvg, socialCardSvg, MARK_DATA_URI, PALETTE,
} from './brand.mjs';

const svgOnly = process.argv.includes('--svg-only');

// ---------- master SVG sources ----------
const svgs = {
  'assets/brand/logo-mark.svg': markSvg({ h: 420 }),
  'assets/brand/logo-mark-mono.svg': monoMarkSvg(PALETTE.midnight),
  'assets/brand/logo-lockup.svg': lockupSvg({ theme: 'light' }),
  'assets/brand/logo-lockup-tagline.svg': lockupSvg({ theme: 'light', tagline: true }),
  'assets/brand/logo-lockup-stacked.svg': lockupSvg({ theme: 'light', stacked: true, tagline: true }),
  'assets/brand/logo-lockup-dark.svg': lockupSvg({ theme: 'dark' }),
  'assets/brand/logo-lockup-sand.svg': lockupSvg({ theme: 'cream' }),
  'assets/brand/social-card.svg': socialCardSvg(),
  'assets/favicon.svg': iconSvg(),
};

// The app shows the mark itself, so the geometry reaches the UI as a generated module
// (a data URI: no request, no CSP exception, no second copy of the artwork to maintain).
const uiMark = `// Generated by tools/make-assets.mjs from the geometry in tools/brand.mjs. Do not edit.
// The KS-LEARN mark as a data URI for CSS backgrounds (CSP img-src data: allows it).
export const MARK_URI = '${MARK_DATA_URI}';
`;

// ---------- PNG jobs: [file, source SVG, pixel width, background] ----------
const pngs = [
  ['assets/icon-192.png', svgs['assets/favicon.svg'], 192, null],
  ['assets/icon-512.png', svgs['assets/favicon.svg'], 512, null],
  ['assets/icon-maskable-512.png', iconSvg({ maskable: true }), 512, null],
  ['assets/apple-touch-icon.png', iconSvg({ bleed: true }), 180, null],
  ['assets/brand/app-icon-1024.png', iconSvg({ maskable: false }), 1024, null],
  ['assets/brand/app-icon-maskable-512.png', iconSvg({ maskable: true }), 512, null],
  ['assets/brand/logo-mark.png', markSvg({ h: 420 }), 1024, PALETTE.cream],
  ['assets/brand/logo-mark-transparent.png', markSvg({ h: 420 }), 1024, null],
  ['assets/brand/logo-lockup.png', svgs['assets/brand/logo-lockup.svg'], 1600, null],
  ['assets/brand/logo-lockup-tagline.png', svgs['assets/brand/logo-lockup-tagline.svg'], 1600, null],
  ['assets/brand/logo-lockup-stacked.png', svgs['assets/brand/logo-lockup-stacked.svg'], 1000, null],
  ['assets/brand/logo-lockup-dark.png', svgs['assets/brand/logo-lockup-dark.svg'], 1600, null],
  ['assets/brand/social-card.png', svgs['assets/brand/social-card.svg'], 1200, null],
];

for (const [path, svg] of Object.entries(svgs)) {
  mkdirSync(path.split('/').slice(0, -1).join('/'), { recursive: true });
  writeFileSync(path, svg);
}
writeFileSync('src/ui/mark.js', uiMark);
console.log(`brand: wrote ${Object.keys(svgs).length} SVG sources + src/ui/mark.js`);
if (svgOnly) process.exit(0);

// ---------- renderer ----------
let Resvg = null;
try { ({ Resvg } = await import('@resvg/resvg-js')); } catch { /* not installed */ }
if (!Resvg) {
  console.log('brand: no renderer (@resvg/resvg-js) — SVG sources are up to date, PNGs skipped');
  process.exit(0);
}

// Webfonts, when installed next to this repo, keep the wordmark and the Hindi tagline honest.
const fontFiles = [];
for (const pkg of ['inter', 'noto-sans-devanagari']) {
  const dir = `node_modules/@expo-google-fonts/${pkg}`;
  if (!existsSync(dir)) continue;
  const walk = d => readdirSync(d, { withFileTypes: true }).flatMap(e =>
    e.isDirectory() ? walk(join(d, e.name)) : e.name.endsWith('.ttf') ? [join(d, e.name)] : []);
  fontFiles.push(...walk(dir).filter(f => /_(400|500|600|700|800|900|300)(Regular|Medium|SemiBold|Bold|ExtraBold|Black)?\.ttf$/.test(f)
    || /(400|500|600|700|800|900)[A-Za-z]*\.ttf$/.test(f)));
}

for (const [path, svg, width, bg] of pngs) {
  const r = new Resvg(svg, {
    fitTo: { mode: 'width', value: width },
    background: bg ? bg : 'rgba(0,0,0,0)',
    font: { fontFiles, loadSystemFonts: true, defaultFontFamily: 'Inter' },
  });
  mkdirSync(path.split('/').slice(0, -1).join('/'), { recursive: true });
  writeFileSync(path, r.render().asPng());
}
console.log(`brand: rendered ${pngs.length} PNGs (${fontFiles.length} font files loaded)`);
